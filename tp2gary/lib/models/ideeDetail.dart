class IdeeDetail {
  final int id;
  final String title;
  final String description;
  final String notes;
  final String imageUrl;
  final String genre;
  final String tuning;
  final String bpm;
  final String difficulty;
  IdeeDetail({
    required this.id,
    required this.title,
    required this.description,
    required this.notes,
    required this.imageUrl,
    required this.genre,
    required this.tuning,
    required this.bpm,
    required this.difficulty,
  });
}
